import importlib.machinery
import importlib.util
import io
import stat
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
HOOK_PATH = str(ROOT / "scripts" / "80-flat-boot-menu")
LOADER = importlib.machinery.SourceFileLoader("flat_boot_menu", HOOK_PATH)
SPEC = importlib.util.spec_from_loader(LOADER.name, LOADER)
hook = importlib.util.module_from_spec(SPEC)
LOADER.exec_module(hook)

TREE = """\
timeout: 1
quiet: yes
interface_branding: Omarchy Bootloader

/Omarchy
comment: Omarchy
comment: machine-id=abc order-priority=50
//linux
comment: kernel-id=linux
protocol: efi
path: boot():/EFI/Linux/linux.efi#aaa
cmdline: quiet
//linux-omarchy
comment: kernel-id=linux-omarchy
protocol: efi
path: boot():/EFI/Linux/omarchy_linux-omarchy.efi#abc123
cmdline: quiet splash
//linux-omarchy-fallback
comment: kernel-id=linux-omarchy-fallback
protocol: efi
path: boot():/EFI/Linux/fallback.efi#beef
//Snapshots
///1
comment: kernel-id=linux-omarchy
protocol: efi
path: boot():/EFI/limine_history/old.efi#fff

/Windows Boot Manager
comment: Windows Boot Manager
comment: order-priority=20
protocol: efi
path: uuid(11111111-2222-3333-4444-555555555555):/EFI/Microsoft/Boot/bootmgfw.efi#deadbeef
"""

FLAT = """\
timeout: 1
quiet: yes
interface_branding: Omarchy Bootloader

default_entry: Omarchy

/Omarchy
### This OS entry is auto-generated by limine-entry-tool
comment: Omarchy
comment: machine-id=abc order-priority=50
comment: kernel-id=linux-omarchy
protocol: efi
path: boot():/EFI/Linux/omarchy_linux-omarchy.efi#abc123
cmdline: quiet splash

/Windows 11
comment: Windows Boot Manager
comment: order-priority=20
protocol: efi
path: uuid(11111111-2222-3333-4444-555555555555):/EFI/Microsoft/Boot/bootmgfw.efi
"""


def flatten(text):
    header, entries = hook.parse(text)
    roots = hook.build_tree(entries)
    omarchy = next(node for node in roots if node["title"] == "Omarchy")
    windows = hook.find_windows(roots)
    kernel = hook.find_kernel(omarchy)
    return hook.render(header, omarchy, kernel, windows)


class ParseTests(unittest.TestCase):
    def test_header_without_entries_is_not_a_menu(self):
        self.assertIsNone(hook.parse("timeout: 5\nquiet: no\n"))

    def test_depth_comes_from_the_leading_slashes(self):
        _, entries = hook.parse(TREE)
        depths = [(entry["depth"], entry["title"]) for entry in entries]
        self.assertEqual(
            depths,
            [
                (1, "Omarchy"),
                (2, "linux"),
                (2, "linux-omarchy"),
                (2, "linux-omarchy-fallback"),
                (2, "Snapshots"),
                (3, "1"),
                (1, "Windows Boot Manager"),
            ],
        )


class KernelTests(unittest.TestCase):
    def test_prefers_linux_omarchy_and_skips_fallback_and_snapshots(self):
        _, entries = hook.parse(TREE)
        omarchy = hook.build_tree(entries)[0]
        kernel = hook.find_kernel(omarchy)
        self.assertEqual(kernel["title"], "linux-omarchy")
        self.assertIn("omarchy_linux-omarchy.efi#abc123", hook.option_line(kernel, "path"))

    def test_uses_the_os_entry_when_it_boots_directly(self):
        text = """\
/Omarchy
protocol: efi
path: boot():/EFI/Linux/omarchy.efi#abc
"""
        _, entries = hook.parse(text)
        omarchy = hook.build_tree(entries)[0]
        self.assertIs(hook.find_kernel(omarchy), omarchy)

    def test_returns_none_when_only_a_fallback_kernel_exists(self):
        text = """\
/Omarchy
comment: Omarchy
//linux-omarchy-fallback
comment: kernel-id=linux-omarchy-fallback
protocol: efi
path: boot():/EFI/Linux/fallback.efi#beef
"""
        _, entries = hook.parse(text)
        omarchy = hook.build_tree(entries)[0]
        self.assertIsNone(hook.find_kernel(omarchy))


class WindowsTests(unittest.TestCase):
    def test_prefers_the_bootmgfw_path_over_a_title_match(self):
        text = """\
/Windows notes
comment: not a boot entry

/Recovery
protocol: efi
path: uuid(abc):/EFI/Microsoft/Boot/bootmgfw.efi#fff
"""
        _, entries = hook.parse(text)
        windows = hook.find_windows(hook.build_tree(entries))
        self.assertEqual(windows["title"], "Recovery")

    def test_chainload_hash_is_removed_and_indentation_stays(self):
        line = "    path: uuid(abc):/EFI/Microsoft/Boot/bootmgfw.efi#deadbeef"
        self.assertEqual(
            hook.chainload_line(line),
            "    path: uuid(abc):/EFI/Microsoft/Boot/bootmgfw.efi",
        )

    def test_comment_with_a_hash_is_left_alone(self):
        line = "comment: order-priority=20 # keep"
        self.assertEqual(hook.chainload_line(line), line)


class RenderTests(unittest.TestCase):
    def test_tree_becomes_two_entries(self):
        self.assertEqual(flatten(TREE), FLAT)

    def test_rendered_menu_renders_again_unchanged(self):
        self.assertEqual(flatten(FLAT), FLAT)

    def test_existing_default_entry_is_replaced_in_place(self):
        text = """\
timeout: 5
default_entry: Windows 11
quiet: no

/Omarchy
comment: Omarchy
protocol: efi
path: boot():/EFI/Linux/omarchy.efi#abc
cmdline: quiet

/Windows 11
protocol: efi
path: uuid(abc):/EFI/Microsoft/Boot/bootmgfw.efi
"""
        rendered = flatten(text)
        self.assertIn("default_entry: Omarchy\nquiet: no\n", rendered)
        self.assertNotIn("default_entry: Windows 11", rendered)
        self.assertNotIn("#", rendered.split("/Windows 11", 1)[1])


class MainTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.path = Path(self.tmp.name) / "limine.conf"
        self.sync = patch.object(hook.os, "sync")
        self.sync.start()
        hook.CONF = self.path

    def tearDown(self):
        self.sync.stop()
        self.tmp.cleanup()

    def run_main(self, text=None):
        if text is not None:
            self.path.write_text(text, encoding="utf-8")
        stdout = io.StringIO()
        stderr = io.StringIO()
        with patch("sys.stdout", stdout), patch("sys.stderr", stderr):
            code = hook.main()
        written = self.path.read_text(encoding="utf-8") if self.path.exists() else None
        return code, stdout.getvalue(), stderr.getvalue(), written

    def test_missing_file_is_left_alone(self):
        code, _stdout, stderr, _written = self.run_main()
        self.assertEqual(code, 0)
        self.assertIn("is missing", stderr)
        self.assertFalse(self.path.exists())

    def test_menu_without_windows_is_left_alone(self):
        text = """\
timeout: 5
/Omarchy
protocol: efi
path: boot():/EFI/Linux/omarchy.efi#abc
"""
        code, _stdout, stderr, result = self.run_main(text)
        self.assertEqual(code, 0)
        self.assertEqual(result, text)
        self.assertIn("Omarchy or Windows is missing", stderr)
        hook.os.sync.assert_not_called()

    def test_tree_is_rewritten(self):
        code, stdout, stderr, result = self.run_main(TREE)
        self.assertEqual(code, 0)
        self.assertEqual(result, FLAT)
        self.assertIn("menu is Omarchy and Windows 11", stdout)
        self.assertEqual(stderr, "")
        hook.os.sync.assert_called_once()
        mode = stat.S_IMODE(self.path.stat().st_mode)
        self.assertEqual(mode, 0o644)

    def test_flat_menu_is_not_rewritten(self):
        code, stdout, stderr, result = self.run_main(FLAT)
        self.assertEqual(code, 0)
        self.assertEqual(result, FLAT)
        self.assertEqual(stdout, "")
        self.assertEqual(stderr, "")
        hook.os.sync.assert_not_called()

    def test_replace_failure_removes_the_temporary_file(self):
        self.path.write_text(TREE, encoding="utf-8")
        with patch.object(hook.os, "replace", side_effect=OSError("disk full")):
            with self.assertRaises(OSError):
                hook.main()
        leftovers = list(Path(self.tmp.name).glob(".limine.conf.*"))
        self.assertEqual(leftovers, [])
        self.assertEqual(self.path.read_text(encoding="utf-8"), TREE)


if __name__ == "__main__":
    unittest.main()
